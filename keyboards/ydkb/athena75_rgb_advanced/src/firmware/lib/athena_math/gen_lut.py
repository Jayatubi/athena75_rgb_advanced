#!/usr/bin/env python3
"""Generate Q15.16 cos/atan tables and the int8 phase sin table."""
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))
FRACTION = 16
N = 512
SHIFT = N.bit_length() - 1


def tofixed(value):
    ival = int(value)
    fval = value - ival
    raw = ((ival << FRACTION) + int(fval * (1 << FRACTION))) & 0xFFFFFFFF
    return "(am_fixed)0x%08X/* %11.8f */" % (raw, value)


def emit_table(file, name, func):
    file.write("\nstatic const am_fixed %s[] =\n{\n" % name)
    for i in range(N):
        if i % 16 == 0:
            file.write("    ")
        file.write(tofixed(func(i)) + ", ")
        if i % 16 == 15:
            file.write("\n")
    file.write("};\n")


def main():
    path = os.path.join(HERE, "athena_math_lut.h")
    with open(path, "w") as f:
        f.write("/* Auto-generated by gen_lut.py — cos + atan only (Q15.16). */\n")
        f.write("#pragma once\n\n")
        f.write("#define AM_LUT_SHIFT %d\n" % SHIFT)
        f.write("#define AM_LUT_SIZE  (1 << AM_LUT_SHIFT)\n")
        emit_table(f, "am_lut_cos", lambda i: math.cos(math.pi * i / N))
        emit_table(f, "am_lut_atan", lambda i: math.atan(-1 + 2.0 * i / N))

    sin8 = [int(round(127 * math.sin(2 * math.pi * i / 256))) for i in range(256)]
    sin8 = [max(-127, min(127, v)) for v in sin8]
    path2 = os.path.join(HERE, "athena_math_sin8.inc")
    with open(path2, "w") as f:
        f.write("/* sin(i*2pi/256)*127 — uint8 phase, wrap free. Generated by gen_lut.py */\n")
        for i in range(0, 256, 16):
            row = ", ".join("%4d" % sin8[j] for j in range(i, i + 16))
            f.write("    %s,\n" % row)
    print("wrote", path)
    print("wrote", path2)


if __name__ == "__main__":
    main()
