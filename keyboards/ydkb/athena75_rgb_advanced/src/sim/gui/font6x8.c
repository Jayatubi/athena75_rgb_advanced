#define ATLAS_COLS 16
#define ATLAS_ROWS 6

SDL_Texture *font_atlas(SDL_Renderer *r) {
    const int w = ATLAS_COLS * FONT_W;
    const int h = ATLAS_ROWS * FONT_H;
    uint32_t *px = SDL_calloc((size_t)(w * h), sizeof(uint32_t));
    if (!px) return NULL;

    for (unsigned g = 0; g < sizeof(k_glyphs) / sizeof(k_glyphs[0]); g++) {
        const int ox = (int)(g % ATLAS_COLS) * FONT_W;
        const int oy = (int)(g / ATLAS_COLS) * FONT_H;
        for (int cx = 0; cx < 5; cx++) {
            uint8_t bits = k_glyphs[g][cx];
            for (int cy = 0; cy < 7; cy++) {
                if (bits & (1u << cy)) px[(oy + cy) * w + ox + cx] = 0xFFFFFFFFu;
            }
        }
    }

    SDL_Surface *surf = SDL_CreateRGBSurfaceWithFormatFrom(px, w, h, 32, w * 4,
                                                           SDL_PIXELFORMAT_ARGB8888);
    SDL_Texture *tex  = surf ? SDL_CreateTextureFromSurface(r, surf) : NULL;
    if (surf) SDL_FreeSurface(surf);
    SDL_free(px);
    if (tex) SDL_SetTextureBlendMode(tex, SDL_BLENDMODE_BLEND);
    return tex;
}

int text_width(int scale, const char *s) {
    return (int)strlen(s) * FONT_W * scale;
}

void draw_text(SDL_Renderer *r, SDL_Texture *atlas, int x, int y, int scale, SDL_Color c,
               const char *fmt, ...) {
    char    buf[512];
    va_list ap;
    va_start(ap, fmt);
    vsnprintf(buf, sizeof(buf), fmt, ap);
    va_end(ap);

    if (!atlas) return;
    SDL_SetTextureColorMod(atlas, c.r, c.g, c.b);
    SDL_SetTextureAlphaMod(atlas, c.a);

    int cx = x;
    for (const char *p = buf; *p; p++) {
        if (*p == '\n') {
            cx = x;
            y += FONT_H * scale;
            continue;
        }
        unsigned g = (unsigned char)*p - 0x20u;
        if (g < sizeof(k_glyphs) / sizeof(k_glyphs[0])) {
            SDL_Rect src = {(int)(g % ATLAS_COLS) * FONT_W, (int)(g / ATLAS_COLS) * FONT_H,
                            FONT_W, FONT_H};
            SDL_Rect dst = {cx, y, FONT_W * scale, FONT_H * scale};
            SDL_RenderCopy(r, atlas, &src, &dst);
        }
        cx += FONT_W * scale;
    }
}
